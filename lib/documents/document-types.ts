/**
 * Enterprise document taxonomy — master-driven classification framework.
 *
 * Every document MUST belong to a structured category. This file is the
 * single source of truth for:
 *  - Document type codes and bilingual labels (EN + AR)
 *  - Category grouping
 *  - Who can upload (employee / HR / payroll / system)
 *  - Which types require expiry monitoring
 *  - Which types are employee-visible vs HR-only by default
 *
 * Do NOT add hardcoded type lists in components — always derive from this
 * registry so changes flow automatically to all UI and validation layers.
 */

// ── Category taxonomy ─────────────────────────────────────────────────────────

export type DocumentCategory =
  | 'IDENTITY'        // Passport, Visa, Emirates ID, Driving License
  | 'EMPLOYMENT'      // Contracts, offer letters, promotion letters, etc.
  | 'PAYROLL'         // Payslips, WPS statements, salary letters
  | 'MEDICAL'         // Medical certificates, fitness certs
  | 'EDUCATION'       // Degrees, professional certs, training
  | 'PERSONAL'        // Marriage cert, birth cert, dependent docs
  | 'BANKING'         // Bank IBAN letter, salary transfer letter
  | 'HR_COMPLIANCE'   // Insurance, labor contracts, company visa
  | 'SUPPORTING'      // Generic attachments

export type SourceType = 'EMPLOYEE' | 'HR' | 'PAYROLL' | 'SYSTEM'

export interface DocumentTypeDef {
  code:               string
  labelEn:            string
  labelAr:            string
  category:           DocumentCategory
  /** Primary uploader role */
  sourceType:         SourceType
  /** Employee can self-upload from ESS */
  employeeUploadable: boolean
  /** Monitor this doc for expiry (send alerts at 90/30/7 days) */
  expiryTracked:      boolean
  /** HR considers this mandatory for all employees */
  defaultMandatory:   boolean
  /** Hidden from employee view by default — HR must explicitly share */
  hrOnlyDefault:      boolean
  /** Employee can replace their own upload of this type */
  employeeCanReplace: boolean
  /** Auto-generated by payroll engine — never manually uploaded */
  payrollGenerated:   boolean
}


// ── Expiry status computation ─────────────────────────────────────────────────

export type ExpiryStatus = 'VALID' | 'EXPIRING_SOON' | 'EXPIRED' | 'NO_EXPIRY'

/** Days before expiry to show EXPIRING_SOON badge. */
export const EXPIRY_WARN_DAYS = 90

/**
 * Compute document status from DB status + expiry date.
 * This ensures fresh status on every page load even if the cron hasn't run.
 */
export function computeDocumentStatus(
  dbStatus: string,
  expiryDate: string | null,
): string {
  if (!expiryDate) return dbStatus === 'VALID' ? 'VALID' : dbStatus
  const today     = new Date()
  today.setHours(0, 0, 0, 0)
  const expiry    = new Date(expiryDate)
  expiry.setHours(0, 0, 0, 0)
  const daysLeft  = Math.floor((expiry.getTime() - today.getTime()) / 86_400_000)
  if (daysLeft < 0)              return 'EXPIRED'
  if (daysLeft <= EXPIRY_WARN_DAYS) return 'EXPIRING_SOON'
  return 'VALID'
}

/** Returns days remaining until expiry (negative = already expired). */
export function daysUntilExpiry(expiryDate: string | null): number | null {
  if (!expiryDate) return null
  const today = new Date()
  today.setHours(0, 0, 0, 0)
  const exp = new Date(expiryDate)
  exp.setHours(0, 0, 0, 0)
  return Math.floor((exp.getTime() - today.getTime()) / 86_400_000)
}

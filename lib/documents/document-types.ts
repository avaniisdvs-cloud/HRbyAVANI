// ── Derived lookup helpers ────────────────────────────────────────────────────

const _byCode = new Map<string, DocumentTypeDef>(
  DOCUMENT_TYPES.map(t => [t.code, t])
)

export function getDocTypeDef(code: string): DocumentTypeDef | undefined {
  return _byCode.get(code)
}

/** Friendly display label for a type code (English). Falls back to formatted code. */
export function getDocTypeLabel(code: string): string {
  return _byCode.get(code)?.labelEn ?? code.replace(/_/g, ' ')
}

/** Arabic label for a type code. Falls back to code. */
export function getDocTypeLabelAr(code: string): string {
  return _byCode.get(code)?.labelAr ?? code.replace(/_/g, ' ')
}

/** Category for a type code. Defaults to SUPPORTING. */
export function getDocTypeCategory(code: string): DocumentCategory {
  return _byCode.get(code)?.category ?? 'SUPPORTING'
}

